import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import { format } from 'date-fns';

export interface PDFExportOptions {
  title: string;
  dateRangeText: string;
  userName: string;
  kpis?: { label: string; value: string | number }[];
  tableHeaders: string[];
  tableData: any[][];
  fileName?: string;
}

export function exportToPDF({
  title,
  dateRangeText,
  userName,
  kpis,
  tableHeaders,
  tableData,
  fileName
}: PDFExportOptions) {
  const doc = new jsPDF();
  const stationName = "Lumina Petrol Station";
  
  // Header
  doc.setFontSize(20);
  doc.setTextColor(155, 28, 46); // Maroon color
  doc.text(stationName, 14, 22);
  
  doc.setFontSize(14);
  doc.setTextColor(50, 50, 50);
  doc.text(title, 14, 32);

  doc.setFontSize(10);
  doc.setTextColor(100, 100, 100);
  doc.text(`Date Range: ${dateRangeText}`, 14, 40);
  doc.text(`Generated by: ${userName}`, 14, 46);
  doc.text(`Generated on: ${format(new Date(), 'PPpp')}`, 14, 52);

  let currentY = 62;

  // KPIs
  if (kpis && kpis.length > 0) {
    doc.setFontSize(12);
    doc.setTextColor(0, 0, 0);
    doc.text("Summary", 14, currentY);
    currentY += 8;

    doc.setFontSize(10);
    kpis.forEach((kpi, idx) => {
      const col = idx % 2 === 0 ? 14 : 110;
      doc.text(`${kpi.label}: ${kpi.value}`, col, currentY);
      if (idx % 2 !== 0) currentY += 6;
    });
    if (kpis.length % 2 !== 0) currentY += 6;
    currentY += 6;
  }

  // Data Table
  if (tableData && tableData.length > 0) {
    autoTable(doc, {
      startY: currentY,
      head: [tableHeaders],
      body: tableData,
      theme: 'grid',
      headStyles: { fillColor: [155, 28, 46] },
      styles: { fontSize: 9 },
    });
  } else {
    doc.setFontSize(12);
    doc.setTextColor(150, 150, 150);
    doc.text("No data available for the selected filters.", 14, currentY + 10);
  }

  // Save the PDF
  const defaultFileName = `petrol-station-${title.toLowerCase().replace(/\s+/g, '-')}-${format(new Date(), 'yyyy-MM-dd')}.pdf`;
  doc.save(fileName || defaultFileName);
}
